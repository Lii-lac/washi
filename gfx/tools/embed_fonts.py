# Subsets the UI fonts and writes them as C arrays (gfx/fontdata.c), so the PC renderer and the Switch app draw with
# exactly the same font data. Run from the gfx folder:  python tools/embed_fonts.py
#
# Font: M PLUS Rounded 1c (SIL Open Font License 1.1), a rounded sans close in spirit to the Switch's own UI font.
# Slots: regular, medium, semibold (= the Bold file). Latin, Latin-1/Extended-A, general punctuation, arrows, kana.
import os
from fontTools import subset

UNICODES = ("U+0020-007E,U+00A0-017F,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2212,U+00B7,U+2190-2193,U+21E7,U+232B,"
            "U+3000-303F,U+3040-309F,U+30A0-30FF")
slots = [("regular", "MPLUSRounded1c-Regular"), ("medium", "MPLUSRounded1c-Medium"), ("semibold", "MPLUSRounded1c-Bold")]
out = ['// Generated by tools/embed_fonts.py. M PLUS Rounded 1c (c) M+ FONTS PROJECT, SIL Open Font License 1.1.',
       '#include "gfx.h"', '']
for key, base in slots:
    src = os.path.join("fonts_src", base + ".ttf")
    dst = os.path.join("fonts_src", base + "-subset.ttf")
    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [1, 2]
    opts.glyph_names = False
    font = subset.load_font(src, opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    subset.save_font(font, dst, opts)
    data = open(dst, "rb").read()
    out.append("const unsigned char font_%s_ttf[%d] = {" % (key, len(data)))
    for i in range(0, len(data), 24):
        out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("const unsigned int font_%s_ttf_len = %d;" % (key, len(data)))
    out.append("")
    print(base, len(data))
open("fontdata.c", "w", newline="\n").write("\n".join(out))
